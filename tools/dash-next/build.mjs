#!/usr/bin/env node
/* The new dashboard's data (redesign phase 3, vault/tasks/2026-11-05-redesign-phase-3-dashboard.md).
 *
 * Until the redesign is released, the live dashboard (index.html) is where a hub is added, dated or archived: its CLASSES,
 * HUBS, ARCHIVED_HUBS and ARCADES arrays and the archive and check-in hours. The new dashboard (next/index.html, drawn by
 * widget/dash.js) is built beside it and must show the same hubs and dates, so this script reads those arrays out of
 * index.html and writes them to next/hubs.js (window.SH_DASH_DATA). CI runs it with --check, so a date changed on the live
 * dashboard without a rebuild fails the PR, the way tools/hub-next/build.mjs keeps the new hubs' content in step.
 *
 *   node tools/dash-next/build.mjs            write next/hubs.js
 *   node tools/dash-next/build.mjs --check    fail if it is stale
 *
 * At the release next/hubs.js becomes the source (edited by hand) and this script is retired.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const CHECK = process.argv.includes("--check");
const html = readFileSync(resolve(ROOT, "index.html"), "utf8");

function between(start, end){
  const a = html.indexOf(start);
  if (a < 0) throw new Error("index.html: can't find `" + start + "`");
  const b = html.indexOf(end, a);
  if (b < 0) throw new Error("index.html: can't find `" + end + "` after `" + start + "`");
  return html.slice(a, b);
}
/* the arrays and the hours, exactly as the live page declares them; nothing else of its script runs */
const src = [
  between("var CLASSES = {", "function examAt("),
  between("var HUB_LABEL", "\n"),
  between("var ARCADES = [", "\n  ];") + "\n  ];"
].join("\n");
const box = {};
vm.runInNewContext(src + "\nthis.out = { CLASSES, HUBS, ARCHIVED_HUBS, CHECKIN_HOUR, ARCHIVE_HOUR, CARD_DAYS, DEBRIEF_DAYS, HUB_LABEL, ARCADES };", box);
const o = box.out;
for (const k of ["CLASSES", "HUBS", "ARCHIVED_HUBS", "HUB_LABEL", "ARCADES"]) if (!o[k] || typeof o[k] !== "object") throw new Error("index.html: " + k + " is missing");
if (!o.HUBS.length) throw new Error("index.html: HUBS is empty");

const classes = {};
for (const [k, c] of Object.entries(o.CLASSES)) classes[k] = { name: c.name, egg: c.egg };   // the ring and the line icon are the old look
const all = o.HUBS.concat(o.ARCHIVED_HUBS);
const data = {
  classes,
  hubs: o.HUBS,
  archived: o.ARCHIVED_HUBS,
  checkinHour: o.CHECKIN_HOUR, archiveHour: o.ARCHIVE_HOUR, cardDays: o.CARD_DAYS, debriefDays: o.DEBRIEF_DAYS,
  labels: o.HUB_LABEL,
  arcades: o.ARCADES,
  /* the hubs with a new version beside the live one (hubs/<id>/next/): the new dashboard opens those */
  next: all.map((h) => h.id).filter((id) => existsSync(resolve(ROOT, "hubs", id, "next", "index.html")))
};
const text = "/* Generated by tools/dash-next/build.mjs from index.html (CLASSES, HUBS, ARCHIVED_HUBS, ARCADES and the archive and\n" +
  "   check-in hours). Do not edit: until the redesign is released, change the live dashboard and rebuild. */\n" +
  "window.SH_DASH_DATA = " + JSON.stringify(data, null, 1) + ";\n";
const file = resolve(ROOT, "next/hubs.js");
if (CHECK) {
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) { console.error("stale: next/hubs.js (run: node tools/dash-next/build.mjs)"); process.exit(1); }
  console.log("next/hubs.js is up to date");
} else {
  writeFileSync(file, text);
  console.log("wrote next/hubs.js (" + (text.length / 1024).toFixed(0) + " KB): " + o.HUBS.length + " hubs, " + o.ARCHIVED_HUBS.length + " archived, " + o.ARCADES.length + " arcades; new versions: " + data.next.join(", "));
}
