#!/usr/bin/env node
// Builds the site's slim database client, widget/vendor/supabase-lite-<version>.js, from entry.mjs and Supabase's own
// postgrest-js and realtime-js. Run it only to change the client's version: the built file is committed (vendored, like
// the full client beside it), so CI and the bundle build never need npm.
//   node tools/bundle/client/build.mjs            (needs npm and network access to the npm registry)
// It installs the pinned packages and esbuild into a temporary folder, bundles, and writes the file with its header.
// Then: node tools/bundle/client/wire-check.mjs (the new build against the real server, next to the full client),
// update the file name in tools/bundle/build.mjs if the version changed, and node tools/bundle/build.mjs.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(HERE, "../../..");
const VERSION = "2.117.2";   /* the supabase-js release the full client (widget/vendor/supabase-<version>.js) is */
const ESBUILD = "0.25.12";
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "sh-client-"));
const run = (cmd, args) => execFileSync(cmd, args, { cwd: tmp, stdio: ["ignore", "pipe", "inherit"] }).toString();
fs.writeFileSync(path.join(tmp, "package.json"), JSON.stringify({ name: "sh-client", private: true }));
run("npm", ["install", "--no-audit", "--no-fund", "--save-exact", `@supabase/postgrest-js@${VERSION}`, `@supabase/realtime-js@${VERSION}`, `esbuild@${ESBUILD}`]);
fs.copyFileSync(path.join(HERE, "entry.mjs"), path.join(tmp, "entry.mjs"));
run(path.join(tmp, "node_modules", ".bin", "esbuild"), ["entry.mjs", "--bundle", "--minify", "--format=iife", "--global-name=supabase", "--target=es2020", "--legal-comments=none", "--outfile=out.js"]);
const ver = p => JSON.parse(fs.readFileSync(path.join(tmp, "node_modules", p, "package.json"), "utf8")).version;
const header = `/* The site's slim database client: rpc(), from() and realtime channels only. GENERATED by tools/bundle/client/build.mjs
   from tools/bundle/client/entry.mjs; do not edit. Built from @supabase/postgrest-js ${ver("@supabase/postgrest-js")}, @supabase/realtime-js ${ver("@supabase/realtime-js")}
   and @supabase/phoenix ${ver("@supabase/phoenix")} (MIT License, Copyright (c) Supabase) and tslib ${ver("tslib")} (0BSD, Copyright (c) Microsoft Corporation). */\n`;
const out = path.join(ROOT, "widget", "vendor", `supabase-lite-${VERSION}.js`);
fs.writeFileSync(out, header + fs.readFileSync(path.join(tmp, "out.js"), "utf8"));
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`✓ ${path.relative(ROOT, out)}: ${Math.round(fs.statSync(out).size / 1024)} KB`);
